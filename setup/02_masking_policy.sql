-- Step 7: Mask resident PII (email, phone) for everyone except TRANSFORMER.
-- Masking policies need Snowflake Enterprise edition (most trial accounts are Enterprise).
-- Run after `dbt build`, as ACCOUNTADMIN.

USE ROLE ACCOUNTADMIN;
USE DATABASE MULTIFAMILY_PRACTICE;
CREATE SCHEMA IF NOT EXISTS GOVERNANCE;

CREATE OR REPLACE MASKING POLICY GOVERNANCE.MASK_PII AS (val STRING) RETURNS STRING ->
  CASE WHEN CURRENT_ROLE() IN ('TRANSFORMER', 'ACCOUNTADMIN') THEN val ELSE '***MASKED***' END;

-- Sensitivity classification with a tag
CREATE TAG IF NOT EXISTS GOVERNANCE.SENSITIVITY ALLOWED_VALUES 'public', 'internal', 'pii';

ALTER TABLE GOLD.DIM_RESIDENT MODIFY COLUMN EMAIL SET MASKING POLICY GOVERNANCE.MASK_PII;
ALTER TABLE GOLD.DIM_RESIDENT MODIFY COLUMN PHONE SET MASKING POLICY GOVERNANCE.MASK_PII;
ALTER TABLE GOLD.DIM_RESIDENT MODIFY COLUMN EMAIL SET TAG GOVERNANCE.SENSITIVITY = 'pii';
ALTER TABLE GOLD.DIM_RESIDENT MODIFY COLUMN PHONE SET TAG GOVERNANCE.SENSITIVITY = 'pii';

GRANT USAGE ON SCHEMA GOLD TO ROLE ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA GOLD TO ROLE ANALYST;

-- Test it:
USE ROLE ANALYST;      SELECT resident_id, email, phone FROM GOLD.DIM_RESIDENT LIMIT 5;  -- masked
USE ROLE TRANSFORMER;  SELECT resident_id, email, phone FROM GOLD.DIM_RESIDENT LIMIT 5;  -- clear

