-- Run this once in a Snowsight worksheet, as ACCOUNTADMIN.
-- Replace YOUR_USERNAME with your Snowflake user name.

USE ROLE ACCOUNTADMIN;

-- Small warehouse that suspends after 60 seconds, so the trial credits last
CREATE WAREHOUSE IF NOT EXISTS PRACTICE_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS MULTIFAMILY_PRACTICE;

-- dbt creates BRONZE, SILVER, GOLD and SNAPSHOTS schemas on the first run
CREATE ROLE IF NOT EXISTS TRANSFORMER;
GRANT USAGE ON WAREHOUSE PRACTICE_WH TO ROLE TRANSFORMER;
GRANT ALL ON DATABASE MULTIFAMILY_PRACTICE TO ROLE TRANSFORMER;
GRANT ROLE TRANSFORMER TO USER YOUR_USERNAME;

-- A read-only role for the masking exercise (step 7 in the README)
CREATE ROLE IF NOT EXISTS ANALYST;
GRANT USAGE ON WAREHOUSE PRACTICE_WH TO ROLE ANALYST;
GRANT USAGE ON DATABASE MULTIFAMILY_PRACTICE TO ROLE ANALYST;
GRANT ROLE ANALYST TO USER YOUR_USERNAME;
